// Generate compact, read-only travel review docs from website seed data.
// Run after editing lib/trip.ts or lib/restaurants.ts. Bookings/overview stay manual.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import ts from 'typescript';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'la-trip-export-'));
const esc=x=>String(x??'').replaceAll('|','／').replaceAll('\n',' ');
try{
 for(const name of ['trip','restaurants']){
  const source=fs.readFileSync(path.join(root,'lib',name+'.ts'),'utf8');
  fs.writeFileSync(path.join(temp,name+'.mjs'),ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
 }
 const {DAYS,DAY_TITLES,INITIAL_ITEMS,ITEM_LINKS}=await import(pathToFileURL(path.join(temp,'trip.mjs')));
 const {RESTAURANTS,HOME_MEALS}=await import(pathToFileURL(path.join(temp,'restaurants.mjs')));
 const header='<!-- Generated by scripts/export-trip-docs.mjs; edit seed data, not this file. -->\n';
 let itinerary=header+'# 日付別 여행 일정\n\n웹사이트 기본 계획에서 생성한 읽기용 문서. 현지시간 기준이며 정확한 공연 시각·운영시간·예약 실적을 보장하지 않는다. 사용자 확인 예약 상태는 [bookings.md](bookings.md)를 우선 확인한다.\n';
 for(const [index,date] of DAYS.entries()){
  itinerary+=`\n## ${date} · ${DAY_TITLES[index]}\n\n| 시간 | 계획 | 구분 | 함께 | 장소 | 메모 |\n|---|---|---|---|---|---|\n`;
  const items=INITIAL_ITEMS.filter(x=>x.day===date).sort((a,b)=>a.time.localeCompare(b.time));
  for(const x of items)itinerary+=`| ${x.time} | ${esc(x.title)} | ${esc(x.status)} | ${x.people.join('·')} | ${esc(x.place)} | ${esc(x.note)} |\n`;
  const links=items.flatMap(x=>(ITEM_LINKS[x.id]??[]).map(l=>`- ${esc(x.title)}: [${esc(l.label)}](${l.url})`));
  if(links.length)itinerary+='\n공식 확인 링크:\n\n'+links.join('\n')+'\n';
 }
 itinerary+='\n## 예약 문서와 구분할 것\n\n일정의 `계획 확정`은 예약 완료가 아니다. 렌터카는 사용자 대화상 Alamo 예약 완료이나 일부 기본 메모는 미확인 문구를 유지한다. 숙소·관광권은 bookings.md에서 확인 상태를 확인한다.\n';
 let food=header+'# 식당·집밥 계획\n\n1인 예상액은 세금·팁 포함, 술·주차 제외. 평점은 과거 조사 참고값으로 실시간 아님. †는 외부 사이트 재인용이며 직접 수집한 Yelp 값도 캐시일 수 있다.\n\n| 날짜·끼니 | 식당·지점 | 구분 | 예약 | 메뉴 | 1인 예산 | Google | Yelp |\n|---|---|---|---|---|---|---|---|\n';
 for(const r of RESTAURANTS){const rating=(v,direct=false)=>v===null?'미확인':v.toFixed(1)+(direct?'':'†');food+=`| ${r.date} ${esc(r.meal)} | [${esc(r.name)}](${r.url}) · ${esc(r.english)} | ${r.status} | ${esc(r.reservation)} | ${esc(r.menu)} | $${r.budget[0]}–${r.budget[1]} | ${rating(r.google)} | ${rating(r.yelp,r.yelpDirect)} |\n`;}
 food+='\n## 장소·선택 메모·평점 출처\n';
 for(const r of RESTAURANTS)food+=`\n- **${r.name}** · ${r.address}。${r.note} 出처: ${r.sources.map((url,i)=>`[${i+1}](${url})`).join(' / ')}\n`;
 food+='\n## 집밥\n\n| 날짜·끼니 | 메뉴 | 1인 예상 | 메모 |\n|---|---|---|---|\n';
 for(const m of HOME_MEALS)food+=`| ${m.date} ${m.meal} | ${m.menu} | ${m.budget} | ${m.note} |\n`;
 food+='\n아침은 요거트·과일·달걀·베이글 등. 10/29 트레이더 조에서 식재료, 11/5에는 기념품 구매. Holbox와 소노라타운은 11/3 점심 택1이며, 10/31 숙소 요리와 살룬 외식도 대안 관계다.\n';
 const dir=path.join(root,'docs/trip');fs.mkdirSync(dir,{recursive:true});
 fs.writeFileSync(path.join(dir,'itinerary.md'),itinerary.replace('日付別','날짜별'));
 fs.writeFileSync(path.join(dir,'food.md'),food.replaceAll('出처','출처'));
 console.log(`Exported ${INITIAL_ITEMS.length} itinerary items and ${RESTAURANTS.length} restaurant candidates.`);
}finally{fs.rmSync(temp,{recursive:true,force:true});}
